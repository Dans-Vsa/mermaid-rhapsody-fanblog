"""Subset Shippori Mincho B1 to the Japanese glyphs this site actually shows.

Fontsource ships ~120 unicode-range slices per weight; declaring them all costs ~130 KB of CSS.
This script scans the source for Japanese characters, subsets only the slices that contain them,
and writes src/assets/fonts/*.woff2 + src/styles/fonts-jp.css. Latin comes from fontsource's
latin-only CSS. Re-run after adding Japanese text:  python tools/build-fonts.py
"""

import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTSOURCE = ROOT / "node_modules" / "@fontsource" / "shippori-mincho-b1"
OUT_FONTS = ROOT / "src" / "assets" / "fonts"
OUT_CSS = ROOT / "src" / "styles" / "fonts-jp.css"
WEIGHTS = (400, 700)

JP = re.compile(r"[　-〿぀-ゟ゠-ヿ一-鿿＀-￯]")


def needed_codepoints():
    chars = set()
    for path in list((ROOT / "src").rglob("*.ts")) + list((ROOT / "src").rglob("*.tsx")) + [ROOT / "index.html"]:
        chars.update(JP.findall(path.read_text(encoding="utf-8")))
    return sorted(ord(c) for c in chars)


def parse_ranges(spec):
    cps = set()
    for part in spec.split(","):
        part = part.strip().upper().removeprefix("U+")
        if "-" in part:
            a, b = part.split("-")
            cps.update(range(int(a, 16), int(b, 16) + 1))
        elif "?" in part:
            cps.update(range(int(part.replace("?", "0"), 16), int(part.replace("?", "F"), 16) + 1))
        else:
            cps.add(int(part, 16))
    return cps


def slices(weight):
    css = (FONTSOURCE / f"{weight}.css").read_text(encoding="utf-8")
    for block in re.findall(r"@font-face\s*{([^}]*)}", css):
        src = re.search(r"url\(\./files/([^)]+?\.woff2)\)", block)
        rng = re.search(r"unicode-range:\s*([^;]+);", block)
        if src and rng:
            yield src.group(1), parse_ranges(rng.group(1))


def unicode_range(cps):
    return ", ".join(f"U+{c:04X}" for c in cps)


def main():
    need = set(needed_codepoints())
    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    for old in OUT_FONTS.glob("smb1-jp-*.woff2"):
        old.unlink()
    rules, total = [], 0
    for weight in WEIGHTS:
        for i, (file, cps) in enumerate(slices(weight)):
            hit = sorted(need & cps)
            if not hit:
                continue
            font = TTFont(FONTSOURCE / "files" / file)
            opts = subset.Options()
            opts.flavor = "woff2"
            opts.layout_features = ["*"]
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=hit)
            sub.subset(font)
            name = f"smb1-jp-{weight}-{i}.woff2"
            font.flavor = "woff2"
            font.save(OUT_FONTS / name)
            size = (OUT_FONTS / name).stat().st_size
            total += size
            rules.append(
                "@font-face {\n"
                "  font-family: 'Shippori Mincho B1';\n"
                "  font-style: normal;\n"
                "  font-display: swap;\n"
                f"  font-weight: {weight};\n"
                f"  src: url('../assets/fonts/{name}') format('woff2');\n"
                f"  unicode-range: {unicode_range(hit)};\n"
                "}\n"
            )
    OUT_CSS.write_text(
        "/* Generated by tools/build-fonts.py: Shippori Mincho B1, only the Japanese glyphs used on the site. */\n\n"
        + "\n".join(rules),
        encoding="utf-8",
    )
    print(f"{len(need)} glyphs, {len(rules)} subset files, {total / 1024:.1f} KB")


if __name__ == "__main__":
    main()
